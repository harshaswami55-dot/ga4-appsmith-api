import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const sourcePath = path.join(ROOT, "appsmith", "sumlink-analytics-dashboard.appsmith.json");
const outputPath = path.join(ROOT, "appsmith", "sumlink-analytics-dashboard-native-cloud.json");

const QUERY_PATHS = {
  ExecutiveSummary: "/api/executive-health",
  AcquisitionSummary: "/api/acquisition-churn",
  OnboardingSummary: "/api/onboarding-funnel",
  GameplaySummary: "/api/gameplay-balancing",
  RetentionSummary: "/api/retention",
};

const API_BASE = "https://sumlink-analytics-api.onrender.com";
const API_KEY = "sumlink-dashboard-key-2026";

const clone = (value) => JSON.parse(JSON.stringify(value));

const stripImportUnsafe = (value) => {
  if (Array.isArray(value)) return value.map(stripImportUnsafe);
  if (!value || typeof value !== "object") return value;

  const cleaned = {};
  for (const [key, child] of Object.entries(value)) {
    if (
      key === "gitSyncId" ||
      key === "applicationId" ||
      key === "workspaceId" ||
      key === "userPermissions" ||
      key === "policyMap" ||
      key === "policies" ||
      key === "userPermissionsForCreate"
    ) {
      continue;
    }
    cleaned[key] = stripImportUnsafe(child);
  }
  return cleaned;
};

const source = JSON.parse(fs.readFileSync(sourcePath, "utf8"));
const pageList = clone(source.pageList ?? []);
const actionList = clone(source.actionList ?? []);
const pageNames = pageList.map(
  (page) => page.unpublishedPage?.name ?? page.publishedPage?.name,
);

const normalisePage = (page) => {
  const name = page.unpublishedPage?.name ?? page.publishedPage?.name;
  const cleaned = stripImportUnsafe(page);

  delete cleaned.id;
  delete cleaned.baseId;
  delete cleaned.basePageId;

  for (const phase of ["unpublishedPage", "publishedPage"]) {
    const pageBody = cleaned[phase];
    if (!pageBody) continue;
    delete pageBody.id;
    delete pageBody.baseId;
    delete pageBody.basePageId;
    pageBody.name = name;
    pageBody.slug = name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
    pageBody.layouts = (pageBody.layouts ?? []).map((layout) => ({
      ...layout,
      id: name,
      deleted: false,
      validOnPageLoadActions: true,
      layoutOnLoadActionErrors: [],
      layoutOnLoadActions: rewriteOnLoadActions(layout.layoutOnLoadActions ?? []),
    }));
  }

  cleaned.deleted = false;
  return cleaned;
};

const actionExportId = (pageName, actionName) =>
  `${pageName.replace(/[^A-Za-z0-9]/g, "")}_${actionName}`;

const actionIdByName = new Map();

const actionPageName = (action) =>
  action.unpublishedAction?.pageId ??
  action.publishedAction?.pageId ??
  pageNames.find((name) => action.unpublishedAction?.basePageId?.includes(name));

for (const action of actionList) {
  const actionName = action.unpublishedAction?.name ?? action.publishedAction?.name ?? action.name;
  const pageName = actionPageName(action);
  actionIdByName.set(actionName, actionExportId(pageName, actionName));
}

function rewriteOnLoadActions(groups) {
  return groups.map((group) =>
    group.map((entry) => ({
      ...stripImportUnsafe(entry),
      id: actionIdByName.get(entry.name) ?? entry.id ?? entry.name,
      name: entry.name,
      pluginType: entry.pluginType ?? "API",
      confirmBeforeExecute: entry.confirmBeforeExecute ?? false,
      jsonPathKeys: entry.jsonPathKeys ?? [],
      timeoutInMillisecond: entry.timeoutInMillisecond ?? 60000,
    })),
  );
}

const normaliseAction = (action) => {
  const actionName = action.unpublishedAction?.name ?? action.publishedAction?.name ?? action.name;
  const pageName = actionPageName(action);
  const exportId = actionExportId(pageName, actionName);
  const cleaned = stripImportUnsafe(action);

  cleaned.id = exportId;
  cleaned.pluginType = "API";
  cleaned.pluginId = "restapi-plugin";
  cleaned.pluginPackageName = "restapi-plugin";
  cleaned.deleted = false;

  for (const phase of ["unpublishedAction", "publishedAction"]) {
    const body = cleaned[phase];
    if (!body) continue;
    delete body.id;
    delete body.baseId;
    delete body.basePageId;
    body.name = actionName;
    body.pageId = pageName;
    body.pluginType = "API";
    body.pluginId = "restapi-plugin";
    body.pluginPackageName = "restapi-plugin";
    body.runBehaviour = body.runBehaviour ?? "ON_PAGE_LOAD";
    body.executeOnLoad = true;
    body.userSetOnLoad = true;
    body.isValid = true;
    body.invalids = [];
    body.datasource = {
      name: "SumlinkAPI",
      pluginId: "restapi-plugin",
      datasourceConfiguration: {
        url: API_BASE,
        headers: [{ key: "x-api-key", value: API_KEY }],
      },
      invalids: [],
      messages: [],
      isAutoGenerated: false,
      deleted: false,
      policyMap: {},
      policies: [],
      userPermissions: [],
    };
    body.actionConfiguration = body.actionConfiguration ?? {};
    const actionPath = QUERY_PATHS[actionName] ?? body.actionConfiguration.path ?? "/";
    body.actionConfiguration.path = actionPath;
    body.actionConfiguration.url = `${API_BASE}${actionPath}`;
    body.actionConfiguration.headers = [{ key: "x-api-key", value: API_KEY }];
    body.actionConfiguration.httpMethod = body.actionConfiguration.httpMethod ?? "GET";
    body.actionConfiguration.timeoutInMillisecond = body.actionConfiguration.timeoutInMillisecond ?? 60000;
    body.actionConfiguration.paginationType = body.actionConfiguration.paginationType ?? "NONE";
    body.actionConfiguration.autoGeneratedHeaders = body.actionConfiguration.autoGeneratedHeaders ?? [];
    body.actionConfiguration.encodeParamsToggle = body.actionConfiguration.encodeParamsToggle ?? true;
    body.actionConfiguration.queryParameters = body.actionConfiguration.queryParameters ?? [];
    body.actionConfiguration.body = body.actionConfiguration.body ?? "";
    body.actionConfiguration.bodyFormData = body.actionConfiguration.bodyFormData ?? [];
    body.actionConfiguration.formData = body.actionConfiguration.formData ?? { apiContentType: "none" };
    body.actionConfiguration.httpVersion = body.actionConfiguration.httpVersion ?? "HTTP11";
    body.actionConfiguration.pluginSpecifiedTemplates =
      body.actionConfiguration.pluginSpecifiedTemplates ?? [{ value: true }];
  }

  return cleaned;
};

const exportedApplication = {
  name: "Sumlink Analytics Dashboard",
  isPublic: false,
  pages: pageNames.map((name, index) => ({ id: name, isDefault: index === 0 })),
  publishedPages: pageNames.map((name, index) => ({ id: name, isDefault: index === 0 })),
  viewMode: false,
  appIsExample: false,
  unreadCommentThreads: 0,
  unpublishedApplicationDetail: {
    appPositioning: { type: "FIXED" },
    navigationSetting: {},
    themeSetting: { sizing: 1, density: 1, appMaxWidth: "LARGE" },
  },
  publishedApplicationDetail: {
    appPositioning: { type: "FIXED" },
    navigationSetting: {},
    themeSetting: { sizing: 1, density: 1, appMaxWidth: "LARGE" },
  },
  color: "#1565C0",
  icon: "line-chart",
  slug: "sumlink-analytics-dashboard",
  unpublishedCustomJSLibs: [],
  publishedCustomJSLibs: [],
  evaluationVersion: 2,
  applicationVersion: 2,
  collapseInvisibleWidgets: true,
  isManualUpdate: false,
  isCommunityTemplate: false,
  deleted: false,
};

const nativeImport = {
  artifactJsonType: "APPLICATION",
  clientSchemaVersion: 2,
  serverSchemaVersion: 12,
  exportedApplication,
  datasourceList: [
    {
      name: "SumlinkAPI",
      pluginId: "restapi-plugin",
      pluginPackageName: "restapi-plugin",
      datasourceConfiguration: {
        url: API_BASE,
        headers: [{ key: "x-api-key", value: API_KEY }],
      },
      invalids: [],
      messages: [],
      isValid: true,
      isConfigured: true,
      isAutoGenerated: false,
      deleted: false,
      policyMap: {},
      policies: [],
      userPermissions: [],
    },
  ],
  customJSLibList: [],
  pageList: pageList.map(normalisePage),
  actionList: actionList.map(normaliseAction),
  actionCollectionList: [],
  editModeTheme: { name: "Default-New", displayName: "Modern", isSystemTheme: true, deleted: false },
  publishedTheme: { name: "Default-New", displayName: "Modern", isSystemTheme: true, deleted: false },
};

fs.writeFileSync(outputPath, `${JSON.stringify(nativeImport, null, 2)}\n`);

console.log(`Created ${outputPath}`);
console.log(`Pages: ${nativeImport.pageList.length}`);
console.log(`Actions: ${nativeImport.actionList.length}`);
console.log(`Size: ${fs.statSync(outputPath).size}`);
